// Table-based DES rounds with QRC's word byte order, PC-2 offset and S2/S4 variants.
// These are file-format constants, not user credentials. Run only off the UI.
Uint8List decryptQrcCloud(Uint8List bytes) {
  if (bytes.isEmpty || bytes.length % 8 != 0) {
    throw const FormatException('Invalid QRC block length');
  }
  final key = '!@#)(*\$%123ZXC!@!@#)(NHL'.codeUnits;
  final schedules = [
    _keys(key.sublist(16, 24)).reversed.toList(),
    _keys(key.sublist(8, 16)),
    _keys(key.sublist(0, 8)).reversed.toList(),
  ];
  final output = Uint8List(bytes.length);
  for (var offset = 0; offset < bytes.length; offset += 8) {
    var word = _read(bytes, offset);
    for (final keys in schedules) {
      final ip = _permute(word, 64, _ip);
      var left = (ip >>> 32) & 0xffffffff;
      var right = ip & 0xffffffff;
      for (final key in keys) {
        final expanded = _permute(right, 32, _expand) ^ key;
        var substituted = 0;
        for (var box = 0; box < 8; box++) {
          final six = (expanded >>> (42 - box * 6)) & 63;
          final row = ((six & 32) >>> 4) | (six & 1);
          final column = (six >>> 1) & 15;
          final value = box == 1 && row == 1 && column == 7
              ? 15
              : box == 3 && row == 3 && column == 5
              ? 10
              : _sboxes[box][row * 16 + column];
          substituted = (substituted << 4) | value;
        }
        final next = left ^ _permute(substituted, 32, _p);
        left = right;
        right = next;
      }
      word = _permute((right << 32) | left, 64, _fp);
    }
    for (var index = 0; index < 8; index++) {
      final swapped = (index ~/ 4) * 4 + 3 - index % 4;
      output[offset + swapped] = (word >>> (56 - index * 8)) & 255;
    }
  }
  return output;
}

int _read(List<int> bytes, int offset) {
  var value = 0;
  for (var index = 0; index < 8; index++) {
    final swapped = (index ~/ 4) * 4 + 3 - index % 4;
    value = (value << 8) | bytes[offset + swapped];
  }
  return value;
}

int _permute(int value, int bits, List<int> table) {
  var output = 0;
  for (final position in table) {
    output =
        (output << 1) |
        (position > bits ? 0 : (value >>> (bits - position)) & 1);
  }
  return output;
}

List<int> _keys(List<int> bytes) {
  final key = _permute(_read(bytes, 0), 64, _pc1);
  var c = key >>> 28, d = key & 0xfffffff;
  final result = <int>[];
  for (final shift in _shifts) {
    c = ((c << shift) | (c >>> (28 - shift))) & 0xfffffff;
    d = ((d << shift) | (d >>> (28 - shift))) & 0xfffffff;
    result.add(_permute((c << 28) | d, 56, _qrcPc2));
  }
  return result;
}

