class ProjectChangelogEntry {
  const ProjectChangelogEntry({
    required this.version,
    required this.date,
    this.features = const [],
    this.fixes = const [],
    this.optimizations = const [],
  });

  final String version;
  final String date;
  final List<String> features;
  final List<String> fixes;
  final List<String> optimizations;

  Iterable<String> get allItems sync* {
    yield* features;
    yield* fixes;
    yield* optimizations;
  }
}

